#!/usr/bin/env python3
"""
Writes ghost/embed.html: exactly what goes in the Ghost HTML card on
https://www.marbleheadindependent.com/ma-06-general/.

It takes the <div id="ma06-app"> block from index.html (nothing from the
<head>, no Open Graph tags, no <body> wrapper, since Ghost sets those) and
wraps it with a script that holds the uploaded files' URLs, loads
styles.css, points the nameplate, pins the data files and loads app.js.

File URLs come from ghost/manifest.json, which tools/publish_ghost.py
writes after each upload (Ghost gives a renamed URL when a file name
repeats, so the data files are pinned by exact URL rather than a folder).
Without a manifest the embed assumes one folder, MA06_BASE below.

    python3 tools/make_embed.py              # from ghost/manifest.json if present
    python3 tools/make_embed.py --base URL   # one folder, no manifest
"""
import argparse
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_BASE = "https://www.marbleheadindependent.com/content/files/ma06-general/"
PAGE_URL = "https://www.marbleheadindependent.com/ma-06-general/"
MANIFEST = os.path.join(ROOT, "ghost", "manifest.json")

FILE_KEYS = {
    "styles": "styles.css", "script": "app.js", "dashboard.json": "data/dashboard.json",
    "build_log.json": "data/build_log.json", "copy.json": "data/copy.json",
    "us-states-paths.json": "data/us-states-paths.json", "nameplate": "assets/images/nameplate-horizontal.png",
}

HEAD = """<!-- MA-06 general election campaign finance dashboard: Ghost HTML card.
     Generated by tools/make_embed.py from index.html; do not hand-edit the
     markup below, edit index.html and rerun the script. The page lives at
     {page}. -->
<script>
  /* The one place that says where the uploaded files are. MA06_BASE is the
     folder; MA06_FILES pins any file whose uploaded name differs (Ghost
     renames a repeat upload, e.g. dashboard-2.json). tools/publish_ghost.py
     rewrites this block after every upload. */
  var MA06_BASE = "{base}";
  var MA06_FILES = {files};
  window.MA06_DATA_BASE = MA06_BASE;
  window.MA06_ASSET_BASE = MA06_BASE;
  window.MA06_DATA_FILES = {{
    "dashboard.json": MA06_FILES["dashboard.json"] || MA06_BASE + "dashboard.json",
    "copy.json": MA06_FILES["copy.json"] || MA06_BASE + "copy.json",
    "us-states-paths.json": MA06_FILES["us-states-paths.json"] || MA06_BASE + "us-states-paths.json"
  }};
  (function () {{
    var link = document.createElement("link");
    link.rel = "stylesheet";
    link.href = MA06_FILES.styles || MA06_BASE + "styles.css";
    document.head.appendChild(link);
  }})();
</script>
"""

TAIL = """<script>
  (function () {
    document.querySelectorAll("#ma06-app [data-ma06-src]").forEach(function (img) {
      var rel = img.getAttribute("data-ma06-src"), name = rel.split("/").pop();
      img.src = MA06_FILES[name] || (name === "nameplate-horizontal.png" && MA06_FILES.nameplate) || MA06_BASE + rel;
    });
    var script = document.createElement("script");
    script.src = MA06_FILES.script || MA06_BASE + "app.js";
    document.body.appendChild(script);
  })();
</script>
"""


def extract_app_div(html):
    start = html.index('<div id="ma06-app">')
    depth = 0
    for m in re.compile(r"<div\b|</div>").finditer(html, start):
        depth += 1 if m.group(0).startswith("<div") else -1
        if depth == 0:
            return html[start:m.end()]
    raise ValueError("unbalanced div in index.html")


def build_embed(base, files):
    with open(os.path.join(ROOT, "index.html"), encoding="utf-8") as f:
        html = f.read()
    block = extract_app_div(html)
    # Every repo-relative image (nameplate, candidate headshots) is pinned at
    # load time from MA06_BASE / MA06_FILES, so the card has no relative paths.
    block = re.sub(r'src="(assets/[^"]+)"', r'src="" data-ma06-src="\1"', block)
    assert ' src="assets/' not in block, "an asset path was not rewritten"
    files_js = json.dumps({k: v for k, v in files.items() if v}, indent=4, sort_keys=True)
    out = HEAD.format(base=base, page=PAGE_URL, files=files_js) + block + "\n" + TAIL
    for bad in ("<head>", "<title>", "og:", "<body"):
        assert bad not in out, f"embed must not contain {bad}"
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", help="folder URL that holds every file (ignores the manifest)")
    ap.add_argument("--manifest", default=MANIFEST)
    args = ap.parse_args()
    base, files = DEFAULT_BASE, {}
    if args.base:
        base = args.base.rstrip("/") + "/"
    elif os.path.exists(args.manifest):
        with open(args.manifest, encoding="utf-8") as f:
            m = json.load(f)
        base = m.get("base", DEFAULT_BASE)
        files = {k: v.get("url") for k, v in m.get("files", {}).items()}
    out = build_embed(base, files)
    os.makedirs(os.path.join(ROOT, "ghost"), exist_ok=True)
    path = os.path.join(ROOT, "ghost", "embed.html")
    with open(path, "w", encoding="utf-8") as f:
        f.write(out)
    print(f"wrote {os.path.relpath(path, ROOT)} ({len(out):,} characters), base {base}, {len([v for v in files.values() if v])} pinned files")


if __name__ == "__main__":
    main()
