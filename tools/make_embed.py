#!/usr/bin/env python3
"""
Writes ghost/embed.html: exactly what gets pasted into the Ghost HTML card
on https://www.marbleheadindependent.com/ma-06-general/.

It takes the <div id="ma06-app"> block from index.html (nothing from the
<head>, no Open Graph tags, no <body> wrapper, since Ghost sets those) and
wraps it with a script that holds the one base URL for the uploaded files,
loads styles.css from it, points the nameplate at it and loads app.js from
it. Re-run after any change to index.html:

    python3 tools/make_embed.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE_URL = "https://www.marbleheadindependent.com/content/files/ma06-general/"
PAGE_URL = "https://www.marbleheadindependent.com/ma-06-general/"

HEAD = """<!-- MA-06 general election campaign finance dashboard: Ghost HTML card.
     Generated by tools/make_embed.py from index.html; do not hand-edit the
     markup below, edit index.html and rerun the script. The page lives at
     {page}. -->
<script>
  /* The one place to change if the uploaded files move. The folder must hold
     styles.css, app.js, data/dashboard.json, data/build_log.json,
     data/copy.json, data/us-states-paths.json and
     assets/images/nameplate-horizontal.png. */
  var MA06_BASE = "{base}";
  window.MA06_DATA_BASE = MA06_BASE + "data/";
  (function () {{
    var link = document.createElement("link");
    link.rel = "stylesheet";
    link.href = MA06_BASE + "styles.css";
    document.head.appendChild(link);
  }})();
</script>
"""

TAIL = """<script>
  (function () {
    var imgs = document.querySelectorAll("#ma06-app [data-ma06-src]");
    for (var i = 0; i < imgs.length; i++) imgs[i].src = MA06_BASE + imgs[i].getAttribute("data-ma06-src");
    var script = document.createElement("script");
    script.src = MA06_BASE + "app.js";
    document.body.appendChild(script);
  })();
</script>
"""


def extract_app_div(html):
    start = html.index('<div id="ma06-app">')
    # Walk to the matching closing </div>.
    depth = 0
    i = start
    pattern = re.compile(r"<div\b|</div>")
    for m in pattern.finditer(html, start):
        depth += 1 if m.group(0).startswith("<div") else -1
        if depth == 0:
            return html[start:m.end()]
    raise ValueError("unbalanced div in index.html")


def main():
    with open(os.path.join(ROOT, "index.html"), encoding="utf-8") as f:
        html = f.read()
    block = extract_app_div(html)
    # Relative asset paths become data attributes the tail script resolves.
    block = block.replace('src="assets/images/nameplate-horizontal.png"', 'src="" data-ma06-src="assets/images/nameplate-horizontal.png"')
    assert ' src="assets/' not in block, "an asset path was not rewritten"
    out = HEAD.format(base=BASE_URL, page=PAGE_URL) + block + "\n" + TAIL
    os.makedirs(os.path.join(ROOT, "ghost"), exist_ok=True)
    path = os.path.join(ROOT, "ghost", "embed.html")
    with open(path, "w", encoding="utf-8") as f:
        f.write(out)
    print(f"wrote {os.path.relpath(path, ROOT)} ({len(out):,} characters)")


if __name__ == "__main__":
    main()
